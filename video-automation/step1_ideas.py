def build_analysis_payload(ideas: list[Idea]) -> list[dict]:
    """Собирает данные по роликам, у которых проставлены просмотры."""
    rows = []
    for idea in ideas:
        views = idea.views_int
        if views is None:
            continue
        rows.append({
            "название": idea.title,
            "надпись": idea.caption,
            "описание": idea.description,
            "просмотры": views,
        })
    return sorted(rows, key=lambda r: r["просмотры"], reverse=True)


def analyze_performance(client: OpenAI, rows: list[dict]) -> dict:
    """Просит GPT вытащить сработавшие паттерны из статистики просмотров."""
    if not rows:
        return {}

    user_prompt = (
        "Вот снятые ролики с просмотрами, отсортированы по убыванию.\n"
        "Найди, что общего у верхних и чего не хватает нижним.\n\n"
        + json.dumps(rows, ensure_ascii=False, indent=2)
    )
    try:
        response = client.chat.completions.create(
            model=config.TEXT_MODEL,
            temperature=0.3,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": ANALYST_SYSTEM},
                {"role": "user", "content": user_prompt},
            ],
        )
        return json.loads(response.choices[0].message.content or "{}")
    except Exception as exc:  # noqa: BLE001 — без аналитики генерация всё равно идёт
        print(f"[WARN] Анализ просмотров не удался ({exc}). Работаю без статистики.")
        return {}


def format_analysis(analysis: dict) -> str:
    if not analysis:
        return (
            "Статистики пока нет — ни у одной идеи не заполнено поле ПРОСМОТРЫ.\n"
            "Придумываю разноплановые идеи, чтобы набрать первые данные."
        )
    works = analysis.get("работает") or []
    fails = analysis.get("не_работает") or []
    verdict = analysis.get("вывод", "")

    lines = []
    if works:
        lines.append("СРАБОТАЛО (усиливать):")
        lines += [f"  + {item}" for item in works]
    if fails:
        lines.append("НЕ СРАБОТАЛО (избегать):")
        lines += [f"  - {item}" for item in fails]
    if verdict:
        lines.append(f"ВЫВОД: {verdict}")
    return "\n".join(lines)


def generate_ideas(
    client: OpenAI,
    count: int,
    analysis: dict,
    existing: list[Idea],
) -> list[dict]:
    """Генерирует новые идеи с учётом аналитики и уже существующих идей."""
    used = [
        {"название": i.title, "надпись": i.caption}
        for i in existing
        if i.title or i.caption
    ]

    parts = [f"Придумай ровно {count} новых идей."]

    if analysis:
        parts.append(
            "АНАЛИТИКА ПО УЖЕ СНЯТЫМ РОЛИКАМ — обязательно опирайся на неё:\n"
            + json.dumps(analysis, ensure_ascii=False, indent=2)
            + "\n\nБольшинство новых идей должны развивать то, что в списке «работает», "
            "но 1-2 идеи сделай экспериментальными в новом направлении, "
            "чтобы находить новые рабочие приёмы."
        )
    else:
        parts.append(
            "Статистики просмотров пока нет. Сделай партию максимально РАЗНОПЛАНОВОЙ: "
            "разные миры и разные эмоции, чтобы по итогам замеров стало видно, "
            "какое направление выстреливает."
        )

    if used:
        parts.append(
            "УЖЕ ИСПОЛЬЗОВАННЫЕ идеи и надписи — не повторяй их и не делай их пересказ:\n"
            + json.dumps(used, ensure_ascii=False, indent=2)
        )

    parts.append(
        "НАПОМИНАНИЕ ПЕРЕД ОТВЕТОМ. Проверь каждую идею по двум пунктам:\n"
        "1) Надпись обращена к ЗРИТЕЛЮ и обещает ему результат или обучение "
        "(«Как сделать такое же фото», «Это фото разорвет твой директ»), "
        "а не рассказывает историю героя от первого лица.\n"
        "2) Сцену реально можно случайно снять на телефон в обычной жизни. "
        "Если в кадре парашют, яхта, тигр, красная дорожка, частный джет или космос — "
        "замени идею на бытовую и правдоподобную."
    )

    response = client.chat.completions.create(
        model=config.TEXT_MODEL,
        temperature=0.95,
        response_format={"type": "json_object"},
        messages=[
            {"role": "system", "content": IDEAS_SYSTEM},
            {"role": "user", "content": "\n\n".join(parts)},
        ],
    )
    data = json.loads(response.choices[0].message.content or "{}")
    return data.get("идеи", []) or []


# Слова, по которым видно, что сцена «нейросетевая», а не бытовая
UNREALISTIC_MARKERS = (
    # экстрим и опасность
    "парашют", "скалолаз", "горящ", "взрыв", "цунами", "лавин",
    # экзотика и фантастика
    "тигр", "льв", "слон", "динозавр", "дракон", "супергеро",
    "космос", "космич", "марс", "луне", "невесомост", "инопланет",
    "подводн", "под водой", "океан", "акул", "джунгл", "пустын",
    # глянцевая роскошь
    "яхт", "джет", "красная дорожка", "обложк", "смокинг", "лимузин",
    "rolls", "royce", "феррари", "ferrari", "миллион долларов", "чемодан денег",
    # исторические и монаршие декорации
    "королев", "король", "трон", "замок", "средневеков", "рыцар", "дворц",
)
# Признаки надписи «от первого лица» — такие не обещают зрителю ничего
FIRST_PERSON_MARKERS = (
    "мама", "папа", "отец", "соседи", "друзья не", "никто не поверил",
    "я жил", "меня перепутали", "мне не поверили", "я сделал",
)


def check_idea(raw: dict) -> list[str]:
    """Возвращает список замечаний к идее. Пустой список = всё в порядке."""
    problems: list[str] = []
    caption = (raw.get("надпись") or "").lower()
    scene = ((raw.get("промпт_фото") or "") + " " + (raw.get("описание") or "")).lower()

    if any(marker in caption for marker in FIRST_PERSON_MARKERS):
        problems.append("надпись от первого лица, а не обещание зрителю")

    hits = [m for m in UNREALISTIC_MARKERS if m in scene]
    if hits:
        problems.append(f"сцена малореалистичная ({', '.join(hits[:3])})")

    words = len((raw.get("надпись") or "").split())
    if words > 10:
        problems.append(f"надпись слишком длинная ({words} слов)")

    return problems


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Анализ ИДЕИ.txt по просмотрам и генерация новых идей."
    )
    parser.add_argument("--count", type=int, default=5, help="Сколько новых идей добавить (по умолчанию 5).")
    parser.add_argument("--only-analyze", action="store_true", help="Только аналитика, без добавления идей.")
    parser.add_argument(
        "--clean", action="store_true",
        help="Проверить уже лежащие в файле НОВЫЕ идеи и забраковать неподходящие.",
    )
    parser.add_argument("--ideas-file", default=str(config.IDEAS_FILE), help="Путь к ИДЕИ.txt")
    args = parser.parse_args()

    config.require_openai_key()
    config.ensure_dirs()

    ideas_path = Path(args.ideas_file).expanduser()
    ideas = load_ideas(ideas_path)

    # --- Чистка старых идей, не прошедших нынешние правила ---
    if args.clean:
        rejected = 0
        for idea in ideas:
            if idea.status != STATUS_NEW:
                continue
            problems = check_idea({
                "надпись": idea.caption,
                "описание": idea.description,
                "промпт_фото": idea.photo_prompt,
            })
            if problems:
                idea.status = STATUS_REJECTED
                rejected += 1
                print(f"  [{idea.number:03d}] отклонена «{idea.caption}»: {'; '.join(problems)}")
        if rejected:
            save_ideas(ideas_path, ideas)
            print(f"\nЗабраковано идей: {rejected}. В работу они больше не пойдут.")
        else:
            print("Все новые идеи прошли проверку — чистить нечего.")
        print()

    print(f"Файл идей: {ideas_path}")
    print(f"Всего идей в файле: {len(ideas)}")
    by_status: dict[str, int] = {}
    for idea in ideas:
        by_status[idea.status] = by_status.get(idea.status, 0) + 1
    if by_status:
        print("По статусам: " + ", ".join(f"{k}={v}" for k, v in by_status.items()))

    client = OpenAI(api_key=config.OPENAI_API_KEY)

    # --- Аналитика по просмотрам ---
    rows = build_analysis_payload(ideas)
    print(f"\nРоликов с заполненными просмотрами: {len(rows)}")
    if rows:
        print("Топ по просмотрам:")
        for row in rows[:5]:
            print(f"  {row['просмотры']:>9,} — {row['название']} | «{row['надпись']}»".replace(",", " "))

    analysis = analyze_performance(client, rows) if rows else {}
    report = format_analysis(analysis)
    print("\n" + report)

    analytics_path = config.CACHE_DIR / "аналитика.txt"
    analytics_path.parent.mkdir(parents=True, exist_ok=True)
    analytics_path.write_text(
        f"Роликов со статистикой: {len(rows)}\n\n{report}\n",
        encoding="utf-8",
    )

    if args.only_analyze:
        print(f"\nОтчёт сохранён: {analytics_path}")
        return

    # --- Генерация новых идей ---
    # Просим с запасом: часть идей отсеется проверкой на реалистичность
    # и на формат надписи, и мы всё равно наберём нужное количество.
    want = args.count
    print(f"\nГенерирую {want} новых идей...")
    raw_ideas = generate_ideas(client, want + 2, analysis, ideas)
    if not raw_ideas:
        print("GPT не вернул ни одной идеи. Попробуйте запустить ещё раз.")
        return

    accepted: list[dict] = []
    for raw in raw_ideas:
        if len(accepted) >= want:
            break
        problems = check_idea(raw)
        if problems:
            print(f"  отбраковано «{raw.get('надпись', '')}»: {'; '.join(problems)}")
            continue
        accepted.append(raw)

    if not accepted:
        print(
            "Все идеи не прошли проверку. Такое бывает редко — просто запустите ещё раз."
        )
        return
    if len(accepted) < want:
        print(f"  прошло проверку {len(accepted)} из {want} — добавляю их.")

    number = next_number(ideas)
    added: list[Idea] = []
    for raw in accepted:
        title = (raw.get("название") or "").strip()
        caption = (raw.get("надпись") or "").strip().strip('"«»')
        if not title or not caption:
            continue
        added.append(Idea(
            number=number,
            status=STATUS_NEW,
            title=title,
            caption=caption,
            description=(raw.get("описание") or "").strip(),
            photo_prompt=(raw.get("промпт_фото") or "").strip(),
            views="",
        ))
        number += 1

    save_ideas(ideas_path, ideas + added)

    print(f"\nДобавлено идей: {len(added)}")
    for idea in added:
        print(f"  [{idea.number:03d}] {idea.title} — «{idea.caption}»")
    print(f"\nФайл обновлён: {ideas_path}")
    print("Дальше: python3 step2_photo.py")


if __name__ == "__main__":
    main()
